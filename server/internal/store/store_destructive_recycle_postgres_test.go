func destructiveRecyclePostgresStore(t *testing.T) (*Store, context.Context) {
	t.Helper()
	dsn := os.Getenv("DESTRUCTIVE_RECYCLE_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set DESTRUCTIVE_RECYCLE_TEST_DATABASE_URL for isolated PostgreSQL tests")
	}
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.ConnConfig.Host != "localhost" && cfg.ConnConfig.Host != "127.0.0.1" && cfg.ConnConfig.Host != "::1" {
		t.Fatal("tests require loopback PostgreSQL")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 40*time.Second)
	t.Cleanup(cancel)
	schema := fmt.Sprintf("test_destructive_recycle_%d", time.Now().UnixNano())
	admin, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	_, err = admin.Exec(ctx, "CREATE SCHEMA "+pgx.Identifier{schema}.Sanitize())
	if err != nil {
		_ = admin.Close(ctx)
		t.Fatal(err)
	}
	t.Cleanup(func() {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cleanupCancel()
		_, _ = admin.Exec(cleanupCtx, "DROP SCHEMA "+pgx.Identifier{schema}.Sanitize()+" CASCADE")
		_ = admin.Close(cleanupCtx)
	})
	// Every connection resolves only our new schema, never live game tables.
	cfg.ConnConfig.RuntimeParams["search_path"] = pgx.Identifier{schema}.Sanitize()
	cfg.MaxConns = 4
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)
	_, err = pool.Exec(ctx, `
		CREATE TABLE player_item_instances(
		 instance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint NOT NULL,
		 template_item_id text NOT NULL, custom_data jsonb DEFAULT '{}', quantity bigint NOT NULL CHECK(quantity > 0),
		 enhance_level integer DEFAULT 0, roll_seed bigint DEFAULT 0, base_snapshot jsonb DEFAULT '{}', affixes jsonb DEFAULT '[]',
		 milestone_affix_claims jsonb DEFAULT '[]', durability integer DEFAULT 100, max_durability integer DEFAULT 100,
		 state text DEFAULT 'inventory', archived_at timestamptz, created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now()
		);
		CREATE TABLE player_equip_slots(instance_id bigint REFERENCES player_item_instances(instance_id), user_id bigint);
		CREATE TABLE player_kitty_equip_slots(instance_id bigint REFERENCES player_item_instances(instance_id), kitty_id bigint);
		CREATE TABLE fishing_trips(user_id bigint, status text, loadout_snapshot_jsonb jsonb);
		CREATE TABLE player_warehouse_change_logs(
		 user_id bigint,event_type text,item_instance_id bigint,template_item_id text,quantity bigint,source_surface text,target_surface text,
		 details jsonb,category text,direction text,subject_type text,subject_id text,item_totals jsonb,instance_ids jsonb,audit_key text,created_at timestamptz
		);
		CREATE UNIQUE INDEX ON player_warehouse_change_logs(audit_key) WHERE audit_key <> '';
	`)
	if err != nil {
		t.Fatal(err)
	}
	s := destructiveRecycleTestStore()
	s.db = pool
	return s, ctx
}

func seedDestructiveRecycleEquipment(t *testing.T, s *Store, ctx context.Context, id int64) {
	t.Helper()
	r := destructiveRecycleTestRow()
	_, err := s.db.Exec(ctx, `INSERT INTO player_item_instances(instance_id,user_id,template_item_id,quantity,base_snapshot,affixes) VALUES($1,42,'shield',1,$2,$3)`, id, r.BaseSnapshot, r.AffixesRaw)
	if err != nil {
		t.Fatal(err)
	}
}

func destructiveRecycleConfirmInputs(q DestructiveRecycleQuote) []DestructiveRecycleInput {
	items := make([]DestructiveRecycleInput, 0, len(q.Items))
	for _, item := range q.Items {
		items = append(items, DestructiveRecycleInput{InstanceID: item.InstanceID, QuoteToken: item.QuoteToken})
	}
	return items
}

func assertDestructiveRecycleDatabase(t *testing.T, s *Store, ctx context.Context, equipment, gold, logs int64) {
	t.Helper()
	var gotEquipment, gotGold, gotLogs int64
	if err := s.db.QueryRow(ctx, `SELECT
		(SELECT count(*) FROM player_item_instances WHERE template_item_id='shield'),
		(SELECT COALESCE(sum(quantity),0) FROM player_item_instances WHERE template_item_id='gold_coin'),
		(SELECT count(*) FROM player_warehouse_change_logs)`).Scan(&gotEquipment, &gotGold, &gotLogs); err != nil {
		t.Fatal(err)
	}
	if gotEquipment != equipment || gotGold != gold || gotLogs != logs {
		t.Fatalf("equipment/gold/logs=(%d,%d,%d), want=(%d,%d,%d)", gotEquipment, gotGold, gotLogs, equipment, gold, logs)
	}
}

func TestDestructiveRecyclePostgresConcurrentExactlyOnce(t *testing.T) {
	s, ctx := destructiveRecyclePostgresStore(t)
	seedDestructiveRecycleEquipment(t, s, ctx, 11)
	quote, err := s.QuoteDestructiveRecycle(ctx, 42, []DestructiveRecycleInput{{InstanceID: 11}})
	if err != nil {
		t.Fatal(err)
	}
	assertDestructiveRecycleDatabase(t, s, ctx, 1, 0, 0)
	start := make(chan struct{})
	results := make(chan error, 2)
	var wg sync.WaitGroup
	for i := 0; i < 2; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			<-start
			_, err := s.DestructiveRecycle(ctx, 42, destructiveRecycleConfirmInputs(quote))
			results <- err
		}()
	}
	close(start)
	wg.Wait()
	close(results)
	success := 0
	for err := range results {
		if err == nil {
			success++
		} else if !errors.Is(err, pgx.ErrNoRows) {
			t.Fatal(err)
		}
	}
	if success != 1 {
		t.Fatalf("successful commits=%d", success)
	}
	assertDestructiveRecycleDatabase(t, s, ctx, 0, 31, 2)
	var affixes int
	if err := s.db.QueryRow(ctx, `SELECT jsonb_array_length(details->'destroyedEquipment'->0->'affixes') FROM player_warehouse_change_logs WHERE target_surface='recycle'`).Scan(&affixes); err != nil || affixes != 1 {
		t.Fatalf("missing original affix audit: %d %v", affixes, err)
	}
}

func TestDestructiveRecyclePostgresBatchRollbackAndOwnership(t *testing.T) {
	s, ctx := destructiveRecyclePostgresStore(t)
	seedDestructiveRecycleEquipment(t, s, ctx, 11)
	seedDestructiveRecycleEquipment(t, s, ctx, 12)
	items := []DestructiveRecycleInput{{InstanceID: 11}, {InstanceID: 12}}
	if _, err := s.QuoteDestructiveRecycle(ctx, 7, items); !errors.Is(err, ErrInstanceNotOwned) {
		t.Fatalf("other owner: %v", err)
	}
	quote, err := s.QuoteDestructiveRecycle(ctx, 42, items)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := s.db.Exec(ctx, `UPDATE player_item_instances SET roll_seed=99 WHERE instance_id=12`); err != nil {
		t.Fatal(err)
	}
	if _, err := s.DestructiveRecycle(ctx, 42, destructiveRecycleConfirmInputs(quote)); !errors.Is(err, ErrDestructiveRecycleChanged) {
		t.Fatalf("stale batch: %v", err)
	}
	assertDestructiveRecycleDatabase(t, s, ctx, 2, 0, 0)
	quote, err = s.QuoteDestructiveRecycle(ctx, 42, items)
	if err != nil {
		t.Fatal(err)
	}
	// Gold grant fails after equipment deletion. The transaction must restore
	// every original affix and emit no audit events.
	if _, err := s.db.Exec(ctx, `ALTER TABLE player_item_instances ADD CONSTRAINT reject_gold CHECK(template_item_id <> 'gold_coin')`); err != nil {
		t.Fatal(err)
	}
	if _, err := s.DestructiveRecycle(ctx, 42, destructiveRecycleConfirmInputs(quote)); err == nil {
		t.Fatal("expected gold grant failure")
	}
	assertDestructiveRecycleDatabase(t, s, ctx, 2, 0, 0)
	var intact int
	if err := s.db.QueryRow(ctx, `SELECT count(*) FROM player_item_instances WHERE jsonb_array_length(affixes)=1`).Scan(&intact); err != nil || intact != 2 {
		t.Fatalf("affixes lost on rollback: %d %v", intact, err)
	}
	if _, err := s.db.Exec(ctx, `ALTER TABLE player_item_instances DROP CONSTRAINT reject_gold`); err != nil {
		t.Fatal(err)
	}
	if _, err := s.DestructiveRecycle(ctx, 42, destructiveRecycleConfirmInputs(quote)); err != nil {
		t.Fatal(err)
	}
	assertDestructiveRecycleDatabase(t, s, ctx, 0, 62, 2)
	var count int
	if err := s.db.QueryRow(ctx, `SELECT jsonb_array_length(details->'destroyedEquipment') FROM player_warehouse_change_logs WHERE target_surface='recycle'`).Scan(&count); err != nil || count != 2 {
		t.Fatalf("batch audit missing items: %d %v", count, err)
	}
}

func TestDestructiveRecyclePostgresRejectsEquipmentReferences(t *testing.T) {
	s, ctx := destructiveRecyclePostgresStore(t)
	seedDestructiveRecycleEquipment(t, s, ctx, 11)
	quote, err := s.QuoteDestructiveRecycle(ctx, 42, []DestructiveRecycleInput{{InstanceID: 11}})
	if err != nil {
		t.Fatal(err)
	}
	for _, statement := range []string{
		`INSERT INTO player_equip_slots VALUES(11,42)`,
		`INSERT INTO player_kitty_equip_slots VALUES(11,7)`,
		`INSERT INTO fishing_trips VALUES(42,'running','{"components":{"rodInstanceId":11}}')`,
	} {
		if _, err := s.db.Exec(ctx, statement); err != nil {
			t.Fatal(err)
		}
		if _, err := s.DestructiveRecycle(ctx, 42, destructiveRecycleConfirmInputs(quote)); err == nil {
			t.Fatal("consumed referenced equipment")
		}
		assertDestructiveRecycleDatabase(t, s, ctx, 1, 0, 0)
		if _, err := s.db.Exec(ctx, `TRUNCATE player_equip_slots,player_kitty_equip_slots,fishing_trips`); err != nil {
			t.Fatal(err)
		}
	}
}

func TestDestructiveRecyclePostgresEnhancedEquipment(t *testing.T) {
	s, ctx := destructiveRecyclePostgresStore(t)
	seedDestructiveRecycleEquipment(t, s, ctx, 11)
	if _, err := s.db.Exec(ctx, `UPDATE player_item_instances SET enhance_level=10,affixes='[]',base_snapshot='{"armor":23}',milestone_affix_claims='[10]' WHERE instance_id=11`); err != nil {
		t.Fatal(err)
	}
	q, err := s.QuoteDestructiveRecycle(ctx, 42, []DestructiveRecycleInput{{InstanceID: 11}})
	if err != nil || q.TotalGold != 31 || q.Items[0].EnhanceLevel != 10 || len(q.Items[0].Affixes) != 0 {
		t.Fatalf("enhanced quote: %+v %v", q, err)
	}
	if _, err := s.db.Exec(ctx, `UPDATE player_item_instances SET enhance_level=11,base_snapshot='{"armor":25}' WHERE instance_id=11`); err != nil {
		t.Fatal(err)
	}
	if _, err := s.DestructiveRecycle(ctx, 42, destructiveRecycleConfirmInputs(q)); !errors.Is(err, ErrDestructiveRecycleChanged) {
		t.Fatalf("enhancement change accepted: %v", err)
	}
	q, err = s.QuoteDestructiveRecycle(ctx, 42, []DestructiveRecycleInput{{InstanceID: 11}})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := s.db.Exec(ctx, `ALTER TABLE player_item_instances ADD CONSTRAINT reject_gold CHECK(template_item_id <> 'gold_coin')`); err != nil {
		t.Fatal(err)
	}
	if _, err := s.DestructiveRecycle(ctx, 42, destructiveRecycleConfirmInputs(q)); err == nil {
		t.Fatal("expected grant failure")
	}
	assertDestructiveRecycleDatabase(t, s, ctx, 1, 0, 0)
	var intact bool
	if err := s.db.QueryRow(ctx, `SELECT enhance_level=11 AND base_snapshot='{"armor":25}' AND milestone_affix_claims='[10]' FROM player_item_instances WHERE instance_id=11`).Scan(&intact); err != nil || !intact {
		t.Fatalf("enhancement lost on rollback: %v %v", intact, err)
	}
	if _, err := s.db.Exec(ctx, `ALTER TABLE player_item_instances DROP CONSTRAINT reject_gold`); err != nil {
		t.Fatal(err)
	}
	if _, err := s.DestructiveRecycle(ctx, 42, destructiveRecycleConfirmInputs(q)); err != nil {
		t.Fatal(err)
	}
	assertDestructiveRecycleDatabase(t, s, ctx, 0, 31, 2)
	var level int
	if err := s.db.QueryRow(ctx, `SELECT (details->'destroyedEquipment'->0->>'enhanceLevel')::integer FROM player_warehouse_change_logs WHERE target_surface='recycle'`).Scan(&level); err != nil || level != 11 {
		t.Fatalf("missing enhancement audit: %d %v", level, err)
	}
}
