func instanceMarketPostgres(t *testing.T) (*Store, context.Context) {
	t.Helper()
	dsn := os.Getenv("INSTANCE_MARKET_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set INSTANCE_MARKET_TEST_DATABASE_URL for isolated PostgreSQL tests")
	}
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.ConnConfig.Host != "localhost" && cfg.ConnConfig.Host != "127.0.0.1" && cfg.ConnConfig.Host != "::1" {
		t.Fatal("requires loopback PostgreSQL")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	t.Cleanup(cancel)
	admin, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	schema := fmt.Sprintf("test_instance_market_%d", time.Now().UnixNano())
	quoted := pgx.Identifier{schema}.Sanitize()
	if _, err = admin.Exec(ctx, "CREATE SCHEMA "+quoted); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		_, _ = admin.Exec(ctx, "DROP SCHEMA "+quoted+" CASCADE")
		_ = admin.Close(ctx)
	})
	cfg.ConnConfig.RuntimeParams["search_path"] = quoted
	cfg.MaxConns = 6
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)
	_, err = pool.Exec(ctx, `
 CREATE TABLE users(id bigint PRIMARY KEY,username text NOT NULL);
 CREATE TABLE player_item_instances(instance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id bigint NOT NULL,template_item_id text NOT NULL,quantity bigint NOT NULL CHECK(quantity>0),custom_data jsonb DEFAULT '{}',base_snapshot jsonb DEFAULT '{}',affixes jsonb DEFAULT '[]',fish_data jsonb DEFAULT '{}',milestone_affix_claims jsonb DEFAULT '[]',enhance_level int DEFAULT 0,roll_seed bigint DEFAULT 0,durability int DEFAULT 100,max_durability int DEFAULT 100,state text DEFAULT 'inventory',archived_at timestamptz,created_at timestamptz DEFAULT now(),updated_at timestamptz DEFAULT now());
 CREATE TABLE player_equip_slots(instance_id bigint,user_id bigint);
 CREATE TABLE player_kitty_equip_slots(instance_id bigint,kitty_id bigint);
 CREATE TABLE fishing_trips(user_id bigint,status text,loadout_snapshot_jsonb jsonb);
 CREATE TABLE fishing_tournaments(id bigint PRIMARY KEY,status text,ends_at timestamptz);
 CREATE TABLE fishing_tournament_entries(tournament_id bigint,fish_instance_id bigint);
 CREATE TABLE market_fee_tiers(scope text,min_total bigint,max_total bigint,fee_bps bigint,priority int,active boolean);
 INSERT INTO market_fee_tiers VALUES('default',0,NULL,500,1,true);
 CREATE TABLE risk_account_transfers(from_user_id bigint,to_user_id bigint,channel text,reference_id bigint,item_id text,quantity bigint,unit_price bigint,total_price bigint,fee_amount bigint,net_amount bigint,price_anchor bigint,occurred_at timestamptz,extra_jsonb jsonb);
 CREATE TABLE player_warehouse_change_logs(user_id bigint,event_type text,item_instance_id bigint,template_item_id text,quantity bigint,source_surface text,target_surface text,details jsonb,category text,direction text,subject_type text,subject_id text,item_totals jsonb,instance_ids jsonb,audit_key text,created_at timestamptz);
 CREATE UNIQUE INDEX ON player_warehouse_change_logs(audit_key) WHERE audit_key<>'';
 `)
	if err != nil {
		t.Fatal(err)
	}
	for _, id := range []int64{marketSeller, marketBuyer, marketBuyer2} {
		if _, err = pool.Exec(ctx, `INSERT INTO users VALUES($1,$2)`, id, fmt.Sprintf("player_%d", id)); err != nil {
			t.Fatal(err)
		}
	}
	migration, err := os.ReadFile(filepath.Join("..", "..", "schema", "migrations", "20260905_market_instance_variants.sql"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err = pool.Exec(ctx, string(migration)); err != nil {
		t.Fatal(err)
	}
	if _, err = pool.Exec(ctx, string(migration)); err != nil {
		t.Fatal("migration replay", err)
	}
	data, err := catalog.Load(filepath.Join("..", "..", "..", "packages", "game-data", "generated", "game-data.json"))
	if err != nil {
		t.Fatal(err)
	}
	data.MarketProfiles = append(data.MarketProfiles, marketpolicy.Profile{ID: "synthetic_v1", SchemaVersion: 1, GroupingVersion: 1, CatalogKeys: []marketpolicy.Key{}, GroupKeys: []marketpolicy.Key{{Source: "instance", Path: "/baseSnapshot", Compare: "exact"}}, Presentation: []marketpolicy.Field{{Key: marketpolicy.Key{Source: "instance", Path: "/baseSnapshot/rate", Compare: "exact"}, LabelKey: "rate", Format: "percent"}}})
	data.Items = append(data.Items, catalog.Item{ID: "unrelated_crystal", EconomyBaseValue: 1, MarketPolicy: &marketpolicy.Policy{FixedPrice: marketpolicy.FixedPrice{Mode: marketpolicy.InstanceVariants, ProfileID: "synthetic_v1"}}})
	registry, defs, err := buildOperationEffectRuntime(data)
	if err != nil {
		t.Fatal(err)
	}
	s := &Store{db: pool, gameData: data, operationEffectRegistry: registry, operationEffectDefinitions: defs}
	for _, id := range []int64{marketBuyer, marketBuyer2} {
		if _, err = pool.Exec(ctx, `INSERT INTO player_item_instances(user_id,template_item_id,quantity) VALUES($1,'gold_coin',100000)`, id); err != nil {
			t.Fatal(err)
		}
	}
	return s, ctx
}
func seedMarketInstance(t *testing.T, s *Store, ctx context.Context, owner int64, item string, base string) int64 {
	t.Helper()
	var id int64
	if err := s.db.QueryRow(ctx, `INSERT INTO player_item_instances(user_id,template_item_id,quantity,base_snapshot) VALUES($1,$2,1,$3) RETURNING instance_id`, owner, item, base).Scan(&id); err != nil {
		t.Fatal(err)
	}
	return id
}
func listMarketInstances(t *testing.T, s *Store, ctx context.Context, owner int64, item, key string, ids ...int64) (int64, []InstanceMarketSelection) {
	t.Helper()
	input := []InstanceMarketSelection{}
	for _, id := range ids {
		input = append(input, InstanceMarketSelection{InstanceID: id})
	}
	quotes, err := s.QuoteInstanceMarket(ctx, owner, input)
	if err != nil {
		t.Fatal(err)
	}
	for i, q := range quotes {
		input[i] = InstanceMarketSelection{InstanceID: q.InstanceID, QuoteToken: q.QuoteToken}
	}
	listing, err := s.CreateInstanceMarketListing(ctx, owner, item, max(int64(1000), s.ItemEconomyBaseValue(item)), input, key, nil)
	if err != nil {
		t.Fatal(err)
	}
	return listing, input
}
func marketPurchase(t *testing.T, s *Store, ctx context.Context, listing int64, quantity int64) InstanceMarketPurchase {
	t.Helper()
	input := InstanceMarketPurchase{ListingID: listing, Quantity: quantity}
	if err := s.db.QueryRow(ctx, `SELECT price,group_key FROM market_instance_listings WHERE id=$1`, listing).Scan(&input.Price, &input.GroupKey); err != nil {
		t.Fatal(err)
	}
	return input
}
func TestInstanceMarketPostgresAnonymousPriceTimePriority(t *testing.T) {
	s, ctx := instanceMarketPostgres(t)
	item := "unrelated_crystal"
	makeListing := func(owner int64, key string) int64 {
		id := seedMarketInstance(t, s, ctx, owner, item, `{"rate":0.104}`)
		listing, _ := listMarketInstances(t, s, ctx, owner, item, key, id)
		return listing
	}
	first := makeListing(marketSeller, "first")
	second := makeListing(marketBuyer2, "second")
	cheap := makeListing(marketBuyer2, "cheap")
	own := makeListing(marketBuyer, "own")
	if _, err := s.db.Exec(ctx, `UPDATE market_instance_listings SET price=CASE WHEN id=$1 THEN 500 ELSE 100 END WHERE id IN ($1,$2)`, cheap, own); err != nil {
		t.Fatal(err)
	}
	input := marketPurchase(t, s, ctx, first, 1)
	rows, err := s.InstanceMarketListings(ctx, item, input.GroupKey, 0, marketBuyer, 0, 30)
	if err != nil || len(rows) != 4 {
		t.Fatalf("listings: %+v %v", rows, err)
	}
	for i, id := range []int64{own, cheap, first, second} {
		if rows[i].ID != id || rows[i].IsOwn != (id == own) || rows[i].CanBuy != (id == cheap) {
			t.Fatalf("priority/ownership: %+v", rows)
		}
	}
	raw, err := json.Marshal(rows)
	if err != nil || strings.Contains(string(raw), "sellerId") || strings.Contains(string(raw), "sellerName") || strings.Contains(string(raw), "player_") {
		t.Fatalf("public identity leak: %s %v", raw, err)
	}
	// A page must not advertise its first row as buyable if a better offer is elsewhere.
	page, err := s.InstanceMarketListings(ctx, item, input.GroupKey, 0, marketBuyer, 2, 1)
	if err != nil || len(page) == 0 || page[0].CanBuy {
		t.Fatalf("page priority: %+v %v", page, err)
	}
	if _, err = s.BuyInstanceMarketListing(ctx, marketBuyer, input, "skip-cheap"); !errors.Is(err, ErrInstanceMarketChanged) {
		t.Fatalf("must reject skipping cheap offer: %v", err)
	}
	if _, err = s.BuyInstanceMarketListing(ctx, marketBuyer, marketPurchase(t, s, ctx, cheap, 1), "buy-cheap"); err != nil {
		t.Fatal(err)
	}
	if _, err = s.BuyInstanceMarketListing(ctx, marketBuyer, marketPurchase(t, s, ctx, second, 1), "skip-first"); !errors.Is(err, ErrInstanceMarketChanged) {
		t.Fatalf("must reject skipping equal-price earlier offer: %v", err)
	}
	if _, err = s.BuyInstanceMarketListing(ctx, marketBuyer, input, "buy-first"); err != nil {
		t.Fatal(err)
	}
	if _, err = s.BuyInstanceMarketListing(ctx, marketBuyer, marketPurchase(t, s, ctx, second, 1), "buy-second"); err != nil {
		t.Fatal(err)
	}
}

func TestInstanceMarketPostgresGroupPartialBuyCancelAndReplay(t *testing.T) {
	s, ctx := instanceMarketPostgres(t)
	a := seedMarketInstance(t, s, ctx, marketSeller, "unrelated_crystal", `{"rate":0.104,"charges":20}`)
	b := seedMarketInstance(t, s, ctx, marketSeller, "unrelated_crystal", `{"charges":20,"rate":0.1040}`)
	c := seedMarketInstance(t, s, ctx, marketBuyer2, "unrelated_crystal", `{"rate":0.104,"charges":20}`)
	d := seedMarketInstance(t, s, ctx, marketSeller, "unrelated_crystal", `{"rate":0.104,"charges":25}`)
	l, selection := listMarketInstances(t, s, ctx, marketSeller, "unrelated_crystal", "list-1", a, b)
	if replay, err := s.CreateInstanceMarketListing(ctx, marketSeller, "unrelated_crystal", 1000, selection, "list-1", func(string, int64) error { return errors.New("pricing changed") }); err != nil || replay != l {
		t.Fatalf("list replay %d %v", replay, err)
	}
	listMarketInstances(t, s, ctx, marketBuyer2, "unrelated_crystal", "list-2", c)
	listMarketInstances(t, s, ctx, marketSeller, "unrelated_crystal", "list-3", d)
	groups, err := s.InstanceMarketGroups(ctx, "unrelated_crystal", "", 0, 30)
	if err != nil || len(groups) != 2 {
		t.Fatalf("groups %+v %v", groups, err)
	}
	found := false
	for _, g := range groups {
		if g.Quantity == 3 && g.SellerCount == 2 {
			found = true
		}
	}
	if !found {
		t.Fatal("equal values across sellers not grouped")
	}
	in := marketPurchase(t, s, ctx, l, 1)
	result, err := s.BuyInstanceMarketListing(ctx, marketBuyer, in, "buy-1")
	if err != nil {
		t.Fatal(err)
	}
	replay, err := s.BuyInstanceMarketListing(ctx, marketBuyer, in, "buy-1")
	if err != nil || replay.Created || result.OrderID != replay.OrderID {
		t.Fatalf("buy replay %+v %v", replay, err)
	}
	in.Quantity = 2
	if _, err = s.BuyInstanceMarketListing(ctx, marketBuyer, in, "buy-1"); !errors.Is(err, ErrDuplicateIdempotency) {
		t.Fatalf("different replay %v", err)
	}
	if err = s.CancelInstanceMarketListing(ctx, marketSeller, l); err != nil {
		t.Fatal(err)
	}
	if err = s.CancelInstanceMarketListing(ctx, marketSeller, l); err != nil {
		t.Fatal(err)
	}
	var owner int64
	var base, state string
	if err = s.db.QueryRow(ctx, `SELECT user_id,base_snapshot::text,state FROM player_item_instances WHERE instance_id=$1`, a).Scan(&owner, &base, &state); err != nil || owner != marketBuyer || state != "inventory" {
		t.Fatalf("original instance not transferred %d %s %v", owner, state, err)
	}
	var data map[string]any
	_ = json.Unmarshal([]byte(base), &data)
	if data["rate"] != .104 {
		t.Fatal("custom data lost")
	}
	if err = s.db.QueryRow(ctx, `SELECT user_id,state FROM player_item_instances WHERE instance_id=$1`, b).Scan(&owner, &state); err != nil || owner != marketSeller || state != "inventory" {
		t.Fatal("remaining instance not returned")
	}
	// Terminal escrow references must not prevent consuming the purchased item.
	if _, err = s.db.Exec(ctx, `DELETE FROM player_item_instances WHERE instance_id=$1`, a); err != nil {
		t.Fatal(err)
	}
	details, err := s.InstanceMarketListingDetails(ctx, marketBuyer, l)
	if err != nil || len(details) != 1 {
		t.Fatalf("immutable purchase history %+v %v", details, err)
	}
}
func TestInstanceMarketPostgresConcurrencyAndRollback(t *testing.T) {
	s, ctx := instanceMarketPostgres(t)
	id := seedMarketInstance(t, s, ctx, marketSeller, "unrelated_crystal", `{"rate":0.104}`)
	l, _ := listMarketInstances(t, s, ctx, marketSeller, "unrelated_crystal", "concurrent", id)
	in := marketPurchase(t, s, ctx, l, 1)
	start := make(chan struct{})
	results := make(chan error, 2)
	var wg sync.WaitGroup
	for _, buyer := range []int64{marketBuyer, marketBuyer2} {
		wg.Add(1)
		go func(b int64) {
			defer wg.Done()
			<-start
			_, err := s.BuyInstanceMarketListing(ctx, b, in, "race")
			results <- err
		}(buyer)
	}
	close(start)
	wg.Wait()
	close(results)
	success := 0
	for err := range results {
		if err == nil {
			success++
		} else if !errors.Is(err, ErrListingNotEnough) {
			t.Fatal(err)
		}
	}
	if success != 1 {
		t.Fatalf("commits %d", success)
	}
	id = seedMarketInstance(t, s, ctx, marketSeller, "unrelated_crystal", `{"rate":0.105}`)
	l, _ = listMarketInstances(t, s, ctx, marketSeller, "unrelated_crystal", "rollback", id)
	in = marketPurchase(t, s, ctx, l, 1)
	if _, err := s.db.Exec(ctx, `ALTER TABLE market_instance_ledger ADD CONSTRAINT reject_settlement CHECK(amount<0) NOT VALID`); err != nil {
		t.Fatal(err)
	}
	if _, err := s.BuyInstanceMarketListing(ctx, marketBuyer, in, "rollback"); err == nil {
		t.Fatal("expected settlement failure")
	}
	var owner int64
	var state string
	if err := s.db.QueryRow(ctx, `SELECT user_id,state FROM player_item_instances WHERE instance_id=$1`, id).Scan(&owner, &state); err != nil || owner != marketSeller || state != "market" {
		t.Fatalf("failed transaction leaked ownership %d %s %v", owner, state, err)
	}
	var count int
	if err := s.db.QueryRow(ctx, `SELECT count(*) FROM market_instance_orders WHERE listing_id=$1`, l).Scan(&count); err != nil || count != 0 {
		t.Fatal("failed order persisted")
	}
	if _, err := s.db.Exec(ctx, `ALTER TABLE market_instance_ledger DROP CONSTRAINT reject_settlement`); err != nil {
		t.Fatal(err)
	}
	if _, err := s.BuyInstanceMarketListing(ctx, marketBuyer, in, "rollback"); err != nil {
		t.Fatal(err)
	}
}
